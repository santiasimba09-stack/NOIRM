package com.noirm.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.noirm.Noirm;
import com.noirm.gore.SeveredLimb;
import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.entity.LivingEntityRenderer;
import net.minecraft.client.renderer.entity.RenderLayerParent;
import net.minecraft.client.renderer.entity.layers.RenderLayer;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.LivingEntity;
import org.joml.Matrix3f;
import org.joml.Matrix4f;

/**
 * Gore marks on the body (see {@code com.noirm.gore.Gore}): bruises, dirt, soot and cuts drawn
 * over the skin as the fighter takes damage. Each kind has three nested stages
 * ({@code textures/entity/gore/<kind>_<1-3>.png}, generated by {@code tools/goregen/gen_gore.py}):
 * the stage reached is drawn fully and the next one fades in, so marks spread and darken as they
 * build. The marks are painted on the skin's outer layer, so they show over clothes too.
 *
 * <p>Also draws the raw stump where a dying body lost a part. Allocation-free: render types and
 * the stage table are built once.
 */
public class GoreMarksLayer<T extends LivingEntity, M extends HumanoidModel<T>> extends RenderLayer<T, M> {
    static final String[] KINDS = {"bruise", "dirt", "soot", "cut"};
    public static final int STAGES = 3;
    /** Below this, the fading-in stage isn't drawn (the shader would cut it out anyway). */
    private static final float MIN_ALPHA = 0.12f;
    private static final RenderType[][] TYPES = new RenderType[KINDS.length][STAGES];
    static final ResourceLocation WOUND = Noirm.id("textures/entity/gore/wound.png");
    private static final RenderType WOUND_TYPE = RenderType.entityCutoutNoCull(WOUND);

    static {
        for (int kind = 0; kind < KINDS.length; kind++) {
            for (int stage = 0; stage < STAGES; stage++) {
                TYPES[kind][stage] = RenderType.entityTranslucent(Noirm.id("textures/entity/gore/" + KINDS[kind] + "_" + (stage + 1) + ".png"));
            }
        }
    }

    public GoreMarksLayer(RenderLayerParent<T, M> parent) {
        super(parent);
    }

    @Override
    public void render(PoseStack poseStack, MultiBufferSource buffers, int light, T entity, float limbSwing, float limbSwingAmount,
                       float partialTick, float ageInTicks, float netHeadYaw, float headPitch) {
        if (entity.isInvisible()) {
            return;
        }
        int packed = GoreClient.marks(entity.getId());
        int overlay = LivingEntityRenderer.getOverlayCoords(entity, 0f);
        M model = getParentModel();
        for (int kind = 0; packed != 0 && kind < KINDS.length; kind++) {
            float level = GoreClient.level(packed, kind);
            if (level <= 0f) {
                continue;
            }
            float s = level * STAGES;
            int full = Math.min(STAGES, (int) s); // stages drawn completely
            float next = s - full;               // how far into the next one
            if (full > 0) {
                model.renderToBuffer(poseStack, buffers.getBuffer(TYPES[kind][full - 1]), light, overlay, 1f, 1f, 1f, 1f);
            }
            if (full < STAGES && next >= MIN_ALPHA) {
                model.renderToBuffer(poseStack, buffers.getBuffer(TYPES[kind][full]), light, overlay, 1f, 1f, 1f, next);
            }
        }
        int severed = GoreClient.severed(entity.getId());
        if (severed != 0 && model instanceof BendyModel<?> bendy) {
            stumps(poseStack, buffers.getBuffer(WOUND_TYPE), light, bendy, severed);
        }
    }

    /** Raw wounds where the parts were: the neck, the shoulders, the hips (in the torso's space). */
    private static void stumps(PoseStack poseStack, VertexConsumer consumer, int light, BendyModel<?> model, int severed) {
        poseStack.pushPose();
        model.body.translateAndRotate(poseStack);
        // Hips: the bottom of the lower torso (y = 12), each leg's half.
        if ((severed & SeveredLimb.Part.RIGHT_LEG.bit()) != 0) {
            horizontal(poseStack, consumer, light, -4f, 0f, 12.02f, -2f, 2f, 1f);
        }
        if ((severed & SeveredLimb.Part.LEFT_LEG.bit()) != 0) {
            horizontal(poseStack, consumer, light, 0f, 4f, 12.02f, -2f, 2f, 1f);
        }
        model.upperTorso.translateAndRotate(poseStack);
        // The upper torso spans y −6…0 here: the neck on top, the shoulders on its sides.
        if ((severed & SeveredLimb.Part.HEAD.bit()) != 0) {
            horizontal(poseStack, consumer, light, -2.5f, 2.5f, -6.02f, -1.8f, 1.8f, -1f);
        }
        if ((severed & SeveredLimb.Part.RIGHT_ARM.bit()) != 0) {
            side(poseStack, consumer, light, -4.02f, -6f, -2f, -1f);
        }
        if ((severed & SeveredLimb.Part.LEFT_ARM.bit()) != 0) {
            side(poseStack, consumer, light, 4.02f, -6f, -2f, 1f);
        }
        poseStack.popPose();
    }

    /** A flat wound facing up ({@code ny} −1, model Y points down) or down (+1) at height {@code y}. */
    static void horizontal(PoseStack poseStack, VertexConsumer consumer, int light, float x0, float x1, float y, float z0, float z1, float ny) {
        Matrix4f pose = poseStack.last().pose();
        Matrix3f normal = poseStack.last().normal();
        float s = 1f / 16f;
        vertex(consumer, pose, normal, x0 * s, y * s, z0 * s, 0f, 0f, light, ny, 0f);
        vertex(consumer, pose, normal, x0 * s, y * s, z1 * s, 0f, 1f, light, ny, 0f);
        vertex(consumer, pose, normal, x1 * s, y * s, z1 * s, 1f, 1f, light, ny, 0f);
        vertex(consumer, pose, normal, x1 * s, y * s, z0 * s, 1f, 0f, light, ny, 0f);
    }

    /** A wound on the side of the torso (where an arm was): 4×4 pixels from {@code y0} down. */
    private static void side(PoseStack poseStack, VertexConsumer consumer, int light, float x, float y0, float z0, float nx) {
        Matrix4f pose = poseStack.last().pose();
        Matrix3f normal = poseStack.last().normal();
        float s = 1f / 16f;
        float y1 = y0 + 4f, z1 = z0 + 4f;
        vertex(consumer, pose, normal, x * s, y0 * s, z0 * s, 0f, 0f, light, 0f, nx);
        vertex(consumer, pose, normal, x * s, y1 * s, z0 * s, 0f, 1f, light, 0f, nx);
        vertex(consumer, pose, normal, x * s, y1 * s, z1 * s, 1f, 1f, light, 0f, nx);
        vertex(consumer, pose, normal, x * s, y0 * s, z1 * s, 1f, 0f, light, 0f, nx);
    }

    private static void vertex(VertexConsumer consumer, Matrix4f pose, Matrix3f normal, float x, float y, float z, float u, float v,
                               int light, float ny, float nx) {
        consumer.vertex(pose, x, y, z).color(255, 255, 255, 255).uv(u, v).overlayCoords(OverlayTexture.NO_OVERLAY).uv2(light)
                .normal(normal, nx, ny, 0f).endVertex();
    }
}
