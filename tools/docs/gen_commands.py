"""Writes docs/COMMANDS.md from the command guide (CommandGuide.java) and the English text.

Run from the repository root after adding a command: python3 tools/docs/gen_commands.py
"""
import json
import re

GUIDE = "src/main/java/com/noirm/command/CommandGuide.java"
LANG = "src/main/resources/assets/noirm/lang/en_us.json"

src = open(GUIDE).read()
lang = json.load(open(LANG))
out = ["# NOIRM commands", "",
       "Every command starts with `/noirm`. In the game, `/noirm help` lists these sections and "
       "`/noirm help <section>` lists their commands; click one to type it. ⚑ = needs cheats (single-player "
       "with cheats on, or an operator). To run one for someone else: `/execute as <player> run noirm …`.", "",
       "_This file is generated by `tools/docs/gen_commands.py` from `CommandGuide.java`._", ""]
section = None
for m in re.finditer(r'section\("(\w+)"\)|\.add\("(\w+)", "([^"]*)", "([^"]*)", (true|false)\)', src):
    if m.group(1):
        section = m.group(1)
        out += ["", f"## {section} — {lang['help.noirm.section.' + section]}", "", "| Command | What it does | Example |", "|---|---|---|"]
    else:
        key, syntax, example, cheats = m.group(2), m.group(3), m.group(4), m.group(5) == "true"
        desc = lang["help.noirm.%s.%s" % (section, key)]
        syntax = syntax.replace("|", "\\|")
        out.append(f"| `{syntax}` | {desc}{' ⚑' if cheats else ''} | `{example}` |")
kits = sorted(k for k in lang if k.startswith("kit.noirm."))
out += ["", "## Kits", "", "`/noirm kit <name>` (data: `data/noirm/kits/<name>.json`):", ""]
out += [f"- `{k[len('kit.noirm.'):]}`: {lang[k]}" for k in kits]
open("docs/COMMANDS.md", "w").write("\n".join(out) + "\n")
print("wrote docs/COMMANDS.md")
